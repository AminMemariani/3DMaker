pub trait EventSink: Send + Sync {
    fn job(&self, view: &JobView);
    fn projects(&self, list: &[ProjectSummary]);
}

/// Event sink that drops everything (tests, headless use).
pub struct NoEvents;
impl EventSink for NoEvents {
    fn job(&self, _: &JobView) {}
    fn projects(&self, _: &[ProjectSummary]) {}
}

pub type ProviderFactory =
    Arc<dyn Fn(ProviderId) -> Result<Arc<dyn Provider>, UserError> + Send + Sync>;

#[derive(Debug, Clone)]
pub struct EngineConfig {
    pub limits: PlyLimits,
    /// Approximate number of splats per object.
    pub splat_budget: usize,
}

impl Default for EngineConfig {
    fn default() -> Self {
        Self {
            limits: PlyLimits::default(),
            splat_budget: design::DEFAULT_SPLATS,
        }
    }
}

/// File names inside a project's directory.
pub const DESIGN_FILE: &str = "design.json";
pub const ANSWER_FILE: &str = "answer.txt";
pub const SPLAT_FILE: &str = "splat.ply";
/// Present in adjusted objects: what to change and where it came from.
pub const ADJUST_FILE: &str = "adjust.json";
/// Splat edit operations returned by the model (splat adjustments).
pub const OPS_FILE: &str = "ops.json";
/// Copy of the source splat for splat adjustments (rebuilds don't depend on the original).
pub const SOURCE_FILE: &str = "source.ply";
/// Header comments that mark y-up splats this app wrote.
const OWN_PLY_MARKS: [&[u8]; 3] = [
    b"generated by 3D Maker",
    b"converted from a mesh by 3D Maker",
    b"adjusted by 3D Maker",
];

/// How an adjustment is carried out.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum AdjustMode {
    /// The source has a design: the model edits it and the splat is rebuilt.
    Design,
    /// Any other splat: the model returns edit operations applied to a copy.
    Splat,
}

#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct AdjustInfo {
    pub source_id: String,
    pub instruction: String,
    pub mode: AdjustMode,
    /// Splat mode: the source's viewer orientation, baked in before editing.
    pub source_view_rotation: [f32; 3],
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Plan {
    /// Ask the model for a design, then build it.
    Full,
    /// Build the saved design again (no model request).
    Rebuild,
}

struct Active {
    project_id: String,
    cancel: CancellationToken,
    report: Arc<(Mutex<Option<CancelReport>>, Notify)>,
}

pub struct Engine {
    store: Arc<Store>,
    lib: Library,
    providers: ProviderFactory,
    events: Arc<dyn EventSink>,
    cfg: EngineConfig,
    active: Mutex<Option<Active>>,
}

/// Why a run stopped before finishing.
enum Halt {
    Failed {
        error: UserError,
        state: ProjectState,
    },
    Cancelled {
        /// The model request was still in flight.
        designing: bool,
    },
}

fn internal(e: impl std::fmt::Display) -> Halt {
    Halt::Failed {
        error: UserError::internal(e.to_string()),
        state: ProjectState::Failed,
    }
}

impl Engine {
    pub fn new(
        store: Arc<Store>,
        lib: Library,
        providers: ProviderFactory,
        events: Arc<dyn EventSink>,
        cfg: EngineConfig,
    ) -> Arc<Self> {
        Arc::new(Self {
            store,
            lib,
            providers,
            events,
            cfg,
            active: Mutex::new(None),
        })
    }

    pub fn store(&self) -> &Store {
        &self.store
    }
    pub fn library(&self) -> &Library {
        &self.lib
    }

    pub fn active_job(&self) -> Option<JobView> {
        let id = self
            .active
            .lock()
            .unwrap()
            .as_ref()
            .map(|a| a.project_id.clone())?;
        let p = self.store.project(&id).ok()?;
        Some(self.view(&p, None))
    }

    pub fn is_busy(&self) -> bool {
        self.active.lock().unwrap().is_some()
    }

    fn design_path(&self, id: &str) -> PathBuf {
        self.lib.project_dir(id).join(DESIGN_FILE)
    }

    fn load_design(&self, id: &str) -> Option<Design> {
        let text = std::fs::read_to_string(self.design_path(id)).ok()?;
        serde_json::from_str(&text).ok()
    }

    fn load_json<T: serde::de::DeserializeOwned>(&self, id: &str, file: &str) -> Option<T> {
        let text = std::fs::read_to_string(self.lib.project_dir(id).join(file)).ok()?;
        serde_json::from_str(&text).ok()
    }

    /// Whether a saved result of the model (design or operations) can be rebuilt.
    fn has_saved_answer(&self, id: &str) -> bool {
        let dir = self.lib.project_dir(id);
        dir.join(DESIGN_FILE).exists()
            || (dir.join(OPS_FILE).exists() && dir.join(SOURCE_FILE).exists())
    }

    /// Starts a prompt-driven adjustment of a finished object. The result is
    /// a new object; the source is never modified.
    pub fn adjust(
        self: &Arc<Self>,
        source_id: &str,
        instruction: &str,
        provider_id: ProviderId,
        client_request_id: &str,
    ) -> Result<String, UserError> {
        let instruction = instruction.trim();
        if instruction.is_empty() || instruction.chars().count() > 1000 {
            return Err(UserError::new(
                ErrorKind::Internal,
                "Describe the change",
                "Type what to change, in under 1,000 characters.",
                NextAction::None,
            ));
        }
        if let Ok(Some(p)) = self.store.project_by_request(client_request_id) {
            return Ok(p.id);
        }
        let src = self
            .store
            .project(source_id)
            .map_err(|_| UserError::internal("That object no longer exists."))?;
        let src_splat = src
            .splat_path
            .clone()
            .filter(|_| src.state == ProjectState::Ready)
            .ok_or_else(|| UserError::internal("Only finished objects can be adjusted."))?;
        let provider = (self.providers)(provider_id)?;
        let mut guard = self.active.lock().unwrap();
        if guard.is_some() {
            return Err(UserError::busy());
        }
        let id = uuid::Uuid::new_v4().to_string();
        let dir = self.lib.project_dir(&id);
        let mode = if self.load_design(source_id).is_some() {
            AdjustMode::Design
        } else {
            AdjustMode::Splat
        };
        let to_user = |e: ProviderError| e.to_user(provider_id);
        std::fs::create_dir_all(&dir).map_err(|e| to_user(ProviderError::from_io(&e)))?;
        match mode {
            AdjustMode::Design => {
                std::fs::copy(self.design_path(source_id), dir.join("base-design.json"))
                    .map_err(|e| to_user(ProviderError::from_io(&e)))?;
            }
            AdjustMode::Splat => {
                verified_copy(
                    Path::new(&src_splat),
                    &dir.join(SOURCE_FILE),
                    src.splat_sha256.as_deref(),
                )
                .map_err(to_user)?;
            }
        }
        let info = AdjustInfo {
            source_id: source_id.to_string(),
            instruction: instruction.to_string(),
            mode,
            source_view_rotation: src.view_rotation,
        };
        let json =
            serde_json::to_vec_pretty(&info).map_err(|e| UserError::internal(e.to_string()))?;
        write_atomic(&dir, &dir.join(ADJUST_FILE), &json, ".cp-").map_err(to_user)?;
        let label: String = src.prompt.chars().take(60).collect();
        let mut row = ProjectRow::new(
            id.clone(),
            format!("{label} → {instruction}"),
            provider_id.as_str(),
        );
        row.client_request_id = Some(client_request_id.to_string());
        self.store
            .insert_project(&row)
            .map_err(|e| UserError::internal(e.to_string()))?;
        let active = self.make_active(&id);
        let cancel = active.cancel.clone();
        *guard = Some(active);
        drop(guard);
        self.emit_projects();
        self.spawn(id.clone(), provider_id, Some(provider), Plan::Full, cancel);
        Ok(id)
    }

    // ---------- public operations ----------

    pub fn start_generation(self: &Arc<Self>, req: GenerateRequest) -> Result<String, UserError> {
        let prompt = req.prompt.trim().to_string();
        if prompt.is_empty() {
            return Err(UserError::new(
                ErrorKind::Internal,
                "Describe your object",
                "Type a short description of one object first.",
                NextAction::None,
            ));
        }
        if prompt.chars().count() > 2000 {
            return Err(UserError::new(
                ErrorKind::Internal,
                "Description too long",
                "Keep the description under 2,000 characters.",
                NextAction::None,
            ));
        }
        // A repeated click with the same request id is the same request.
        if let Ok(Some(p)) = self.store.project_by_request(&req.client_request_id) {
            return Ok(p.id);
        }
        let provider = (self.providers)(req.provider)?;
        let mut guard = self.active.lock().unwrap();
        if guard.is_some() {
            return Err(UserError::busy());
        }
        let id = uuid::Uuid::new_v4().to_string();
        let mut row = ProjectRow::new(id.clone(), prompt, req.provider.as_str());
        row.client_request_id = Some(req.client_request_id.clone());
        self.store
            .insert_project(&row)
            .map_err(|e| UserError::internal(e.to_string()))?;
        let active = self.make_active(&id);
        let cancel = active.cancel.clone();
        *guard = Some(active);
        drop(guard);
        self.emit_projects();
        self.spawn(id.clone(), req.provider, Some(provider), Plan::Full, cancel);
        Ok(id)
    }

    pub fn retry(self: &Arc<Self>, project_id: &str, action: RetryAction) -> Result<(), UserError> {
        let p = self
            .store
            .project(project_id)
            .map_err(|_| UserError::internal("That object no longer exists."))?;
        let provider_id = ProviderId::parse(&p.provider)
            .ok_or_else(|| UserError::internal("Opened files can't be regenerated."))?;
        let opts = self.retry_options(&p);
        let (allowed, plan) = match action {
            RetryAction::Rebuild => (opts.rebuild, Plan::Rebuild),
            RetryAction::Full => (opts.full, Plan::Full),
        };
        if !allowed {
            return Err(UserError::internal(
                "That retry isn't available for this object right now.",
            ));
        }
        let provider = match plan {
            Plan::Full => Some((self.providers)(provider_id)?),
            Plan::Rebuild => None,
        };
        let mut guard = self.active.lock().unwrap();
        if guard.is_some() {
            return Err(UserError::busy());
        }
        let active = self.make_active(project_id);
        let cancel = active.cancel.clone();
        *guard = Some(active);
        drop(guard);
        let _ = self.store.set_state(project_id, ProjectState::Queued, None);
        self.spawn(project_id.to_string(), provider_id, provider, plan, cancel);
        Ok(())
    }

    /// Stops the run. A model request in flight is abandoned (the HTTP
    /// connection is closed, or the Claude Code process is ended).
    pub async fn cancel(&self, project_id: &str) -> CancelReport {
        let (token, report) = {
            let g = self.active.lock().unwrap();
            match g.as_ref() {
                Some(a) if a.project_id == project_id => (a.cancel.clone(), a.report.clone()),
                _ => {
                    return CancelReport {
                        outcome: CancelOutcome::AlreadyFinished,
                        message: "Nothing is running for this object.".into(),
                    };
                }
            }
        };
        token.cancel();
        let deadline = tokio::time::sleep(Duration::from_secs(10));
        tokio::pin!(deadline);
        loop {
            let notified = report.1.notified();
            if let Some(r) = report.0.lock().unwrap().clone() {
                return r;
            }
            tokio::select! {
                _ = notified => {}
                _ = &mut deadline => {
                    return CancelReport {
                        outcome: CancelOutcome::LocalOnly,
                        message: "Stopping is taking longer than expected; the object will not be saved.".into(),
                    };
                }
            }
        }
    }

    /// On startup: clean temp files and mark interrupted objects. Nothing is
    /// sent to a model automatically; a saved design can be rebuilt for free.
    pub fn recover(self: &Arc<Self>) -> usize {
        self.lib.cleanup_partials();
        let Ok(list) = self.store.unfinished_projects() else {
            return 0;
        };
        for p in &list {
            if let Ok(Some(st)) = self.store.latest_stage(&p.id, StageKind::Design) {
                if st.status == StageStatus::Running {
                    let _ = self.store.update_stage(
                        &p.id,
                        StageKind::Design,
                        st.attempt,
                        StageStatus::Failed,
                        None,
                    );
                }
            }
            let e = if self.has_saved_answer(&p.id) {
                UserError::new(
                    ErrorKind::Internal,
                    "Building was interrupted",
                    "3D Maker closed while building this object. The design is saved, so rebuilding is free.",
                    NextAction::Rebuild,
                )
            } else {
                UserError::new(
                    ErrorKind::UnknownOutcome,
                    "Designing was interrupted",
                    "3D Maker closed while the model was designing this object. Ask again to start a new design.",
                    NextAction::RetryAll,
                )
            };
            let _ = self
                .store
                .set_state(&p.id, ProjectState::NeedsAttention, Some(&e));
        }
        self.emit_projects();
        list.len()
    }

    pub fn summaries(&self) -> Vec<ProjectSummary> {
        self.store
            .projects()
            .unwrap_or_default()
            .iter()
            .map(summary)
            .collect()
    }

    pub fn detail(&self, id: &str) -> Result<ProjectDetail, UserError> {
        let p = self
            .store
            .project(id)
            .map_err(|_| UserError::internal("That object no longer exists."))?;
        let model = self
            .store
            .latest_stage(id, StageKind::Design)
            .ok()
            .flatten()
            .map(|s| s.model)
            .filter(|m| !m.is_empty());
        Ok(ProjectDetail {
            summary: summary(&p),
            splat_path: p.splat_path.clone(),
            splat_bytes: p.splat_bytes,
            splat_sha256: p.splat_sha256.clone(),
            sh_degree: p.sh_degree,
            bounds: p.bounds.clone(),
            view_rotation: p.view_rotation,
            model,
            part_count: self.load_design(id).map(|d| d.parts.len()),
            error: p.error.clone(),
            retry: self.retry_options(&p),
        })
    }

    pub fn delete(&self, id: &str) -> Result<(), UserError> {
        if self
            .active
            .lock()
            .unwrap()
            .as_ref()
            .is_some_and(|a| a.project_id == id)
        {
            return Err(UserError::busy());
        }
        self.store
            .delete_project(id)
            .map_err(|e| UserError::internal(e.to_string()))?;
        self.lib.remove_project_dir(id);
        self.emit_projects();
        Ok(())
    }

    /// Byte-for-byte export of the validated splat.
    pub fn export(&self, id: &str, dest: &Path) -> Result<ExportResult, UserError> {
        let p = self
            .store
            .project(id)
            .map_err(|_| UserError::internal("That object no longer exists."))?;
        let src = p
            .splat_path
            .clone()
            .filter(|_| p.state == ProjectState::Ready)
            .ok_or_else(|| {
                UserError::internal("This object has no finished splat to export yet.")
            })?;
        let (bytes, sha) = verified_copy(Path::new(&src), dest, p.splat_sha256.as_deref())
            .map_err(|e| e.to_user(ProviderId::Custom))?;
        Ok(ExportResult {
            saved: true,
            path: Some(dest.display().to_string()),
            bytes: Some(bytes),
            sha256: Some(sha),
        })
    }

    /// Opens a user's file as a new object: a Gaussian splat (.ply) is
    /// validated and copied; a mesh (.obj, .stl) is sampled into splats.
    pub async fn import(&self, src: PathBuf) -> Result<String, UserError> {
        if let Some(kind) = MeshKind::from_path(&src) {
            return self.import_mesh(src, kind).await;
        }
        let limits = self.cfg.limits;
        let check = src.clone();
        let summary = tokio::task::spawn_blocking(move || ply::validate_file(&check, &limits))
            .await
            .map_err(|e| UserError::internal(e.to_string()))?
            .map_err(|e| {
                UserError::new(
                    ErrorKind::InvalidAsset,
                    "This file can't be opened",
                    e.to_string(),
                    NextAction::None,
                )
            })?;
        let id = uuid::Uuid::new_v4().to_string();
        let dest = self.lib.project_dir(&id).join(SPLAT_FILE);
        let expected = summary.sha256.clone();
        let name = src
            .file_name()
            .map(|n| n.to_string_lossy().to_string())
            .unwrap_or_else(|| "Opened splat file".into());
        let own = header_has_mark(&src);
        let d2 = dest.clone();
        tokio::task::spawn_blocking(move || verified_copy(&src, &d2, Some(&expected)))
            .await
            .map_err(|e| UserError::internal(e.to_string()))?
            .map_err(|e| e.to_user(ProviderId::Custom))?;
        let mut row = ProjectRow::new(id.clone(), name, "import");
        // Most splat files use the 3DGS y-down convention; ours are y-up.
        row.view_rotation = if own { [0.0; 3] } else { [180.0, 0.0, 0.0] };
        self.store
            .insert_project(&row)
            .map_err(|e| UserError::internal(e.to_string()))?;
        self.store
            .mark_ready(&id, &dest.display().to_string(), &summary)
            .map_err(|e| UserError::internal(e.to_string()))?;
        self.emit_projects();
        Ok(id)
    }

    async fn import_mesh(&self, src: PathBuf, kind: MeshKind) -> Result<String, UserError> {
        let budget = self.cfg.splat_budget;
        let s2 = src.clone();
        let bytes = tokio::task::spawn_blocking(move || {
            mesh::load(&s2, kind).map(|t| mesh::to_ply(&t, budget))
        })
        .await
        .map_err(|e| UserError::internal(e.to_string()))?
        .map_err(|e| {
            UserError::new(
                ErrorKind::InvalidAsset,
                "This model can't be opened",
                e.to_string(),
                NextAction::None,
            )
        })?;
        let id = uuid::Uuid::new_v4().to_string();
        let name = src
            .file_name()
            .map(|n| n.to_string_lossy().to_string())
            .unwrap_or_else(|| "Opened model".into());
        let mut row = ProjectRow::new(id.clone(), name, "import");
        row.view_rotation = kind.view_rotation();
        self.store
            .insert_project(&row)
            .map_err(|e| UserError::internal(e.to_string()))?;
        let res = self
            .commit_splat(&id, ProviderId::Custom, bytes, &CancellationToken::new())
            .await;
        if let Err(Halt::Failed { error, .. }) = res {
            let _ = self.store.delete_project(&id);
            self.lib.remove_project_dir(&id);
            return Err(error);
        }
        self.emit_projects();
        Ok(id)
    }

    pub fn save_thumbnail(&self, id: &str, png: &[u8]) -> Result<(), UserError> {
        if png.len() > 4 * 1024 * 1024 || !png.starts_with(&[0x89, b'P', b'N', b'G']) {
            return Err(UserError::internal("Thumbnail must be a PNG under 4 MB."));
        }
        let p = self
            .store
            .project(id)
            .map_err(|_| UserError::internal("That object no longer exists."))?;
        if p.thumb_path.is_some() {
            return Ok(());
        }
        let dir = self.lib.project_dir(id);
        let dest = dir.join("thumb.png");
        write_atomic(&dir, &dest, png, ".cp-").map_err(|e| e.to_user(ProviderId::Custom))?;
        self.store
            .set_thumb(id, &dest.display().to_string())
            .map_err(|e| UserError::internal(e.to_string()))?;
        self.emit_projects();
        Ok(())
    }

    // ---------- pipeline ----------

    fn make_active(&self, id: &str) -> Active {
        Active {
            project_id: id.to_string(),
            cancel: CancellationToken::new(),
            report: Arc::new((Mutex::new(None), Notify::new())),
        }
    }

    fn spawn(
        self: &Arc<Self>,
        id: String,
        pid: ProviderId,
        provider: Option<Arc<dyn Provider>>,
        plan: Plan,
        cancel: CancellationToken,
    ) {
        let me = self.clone();
        tokio::spawn(async move {
            let res = me.run(&id, pid, provider, plan, &cancel).await;
            me.finish(&id, pid, res);
            {
                let mut g = me.active.lock().unwrap();
                if g.as_ref().is_some_and(|a| a.project_id == id) {
                    *g = None;
                }
            }
            me.emit_projects();
        });
    }

    fn finish(&self, id: &str, pid: ProviderId, res: Result<(), Halt>) {
        let report = match res {
            Ok(()) => None,
            Err(Halt::Failed { error, state }) => {
                let _ = self.store.set_state(id, state, Some(&error));
                None
            }
            Err(Halt::Cancelled { designing }) => {
                let name = pid.display_name();
                let report = match (designing, pid.bills_per_call()) {
                    (true, true) => CancelReport {
                        outcome: CancelOutcome::LocalOnly,
                        message: format!("Stopped. {name} may still bill for the part of the answer it had already written."),
                    },
                    (true, false) => CancelReport {
                        outcome: CancelOutcome::Confirmed,
                        message: format!("Stopped. {name} is no longer working on it."),
                    },
                    (false, _) => CancelReport {
                        outcome: CancelOutcome::Confirmed,
                        message: "Stopped before the object was saved. The design is kept, so rebuilding is free.".into(),
                    },
                };
                let _ = self.store.set_state(id, ProjectState::Cancelled, None);
                if let Some(a) = self
                    .active
                    .lock()
                    .unwrap()
                    .as_ref()
                    .filter(|a| a.project_id == id)
                {
                    *a.report.0.lock().unwrap() = Some(report.clone());
                    a.report.1.notify_waiters();
                }
                Some(report)
            }
        };
        if let Ok(p) = self.store.project(id) {
            self.events.job(&self.view(&p, report));
        }
    }

    fn set_state(&self, id: &str, state: ProjectState) {
        let _ = self.store.set_state(id, state, None);
        if let Ok(row) = self.store.project(id) {
            self.events.job(&self.view(&row, None));
        }
    }

    async fn run(
        &self,
        id: &str,
        pid: ProviderId,
        provider: Option<Arc<dyn Provider>>,
        plan: Plan,
        cancel: &CancellationToken,
    ) -> Result<(), Halt> {
        let dir = self.lib.project_dir(id);
        std::fs::create_dir_all(&dir).map_err(|e| Halt::Failed {
            error: ProviderError::from_io(&e).to_user(pid),
            state: ProjectState::Failed,
        })?;
        let missing = || Halt::Failed {
            error: UserError::new(
                ErrorKind::InvalidDesign,
                "The saved answer is missing",
                "Ask the model again.",
                NextAction::RetryAll,
            ),
            state: ProjectState::Failed,
        };
        let adjust: Option<AdjustInfo> = self.load_json(id, ADJUST_FILE);
        if let Some(info) = adjust.as_ref().filter(|a| a.mode == AdjustMode::Splat) {
            let ops: adjust::Plan = match (plan, provider) {
                (Plan::Full, Some(p)) => {
                    let summary = self.splat_summary(id, info, pid).await?;
                    let user = adjust::user_prompt(&summary, &info.instruction);
                    self.ask(
                        id,
                        pid,
                        p,
                        &adjust::system_prompt(),
                        &user,
                        OPS_FILE,
                        cancel,
                        |t| adjust::parse(t).map_err(|e| e.to_string()),
                    )
                    .await?
                }
                (Plan::Full, None) => return Err(internal("no provider for this request")),
                (Plan::Rebuild, _) => self.load_json(id, OPS_FILE).ok_or_else(missing)?,
            };
            return self.apply_ops(id, pid, info, &ops, cancel).await;
        }
        let design = match (plan, provider) {
            (Plan::Full, Some(p)) => {
                let (system, user) = match &adjust {
                    Some(info) => {
                        let base: Design =
                            self.load_json(id, "base-design.json").ok_or_else(missing)?;
                        (
                            design::edit_system_prompt(),
                            design::edit_user_prompt(&base, &info.instruction),
                        )
                    }
                    None => {
                        let row = self.store.project(id).map_err(internal)?;
                        (design::system_prompt(), design::user_prompt(&row.prompt))
                    }
                };
                self.ask(id, pid, p, &system, &user, DESIGN_FILE, cancel, |t| {
                    design::parse(t).map_err(|e| e.to_string())
                })
                .await?
            }
            (Plan::Full, None) => return Err(internal("no provider for this request")),
            (Plan::Rebuild, _) => self.load_design(id).ok_or_else(missing)?,
        };
        self.build(id, pid, &design, cancel).await
    }

    /// Summary of the source splat (in viewer space) for the model.
    async fn splat_summary(
        &self,
        id: &str,
        info: &AdjustInfo,
        pid: ProviderId,
    ) -> Result<String, Halt> {
        let src = self.lib.project_dir(id).join(SOURCE_FILE);
        let (limits, rot) = (self.cfg.limits, info.source_view_rotation);
        tokio::task::spawn_blocking(move || {
            let mut t = ply::load_table(&src, &limits).map_err(|e| e.to_string())?;
            adjust::bake_view_rotation(&mut t, rot).map_err(|e| e.to_string())?;
            adjust::summarize(&t).map_err(|e| e.to_string())
        })
        .await
        .map_err(internal)?
        .map_err(|e| Halt::Failed {
            error: ProviderError::Io(format!("the source object couldn't be read: {e}"))
                .to_user(pid),
            state: ProjectState::Failed,
        })
    }

    /// Applies saved operations to the source copy and commits the result.
    async fn apply_ops(
        &self,
        id: &str,
        pid: ProviderId,
        info: &AdjustInfo,
        ops: &adjust::Plan,
        cancel: &CancellationToken,
    ) -> Result<(), Halt> {
        if cancel.is_cancelled() {
            return Err(Halt::Cancelled { designing: false });
        }
        self.set_state(id, ProjectState::Building);
        let dir = self.lib.project_dir(id);
        let (limits, rot, ops2, d2) = (
            self.cfg.limits,
            info.source_view_rotation,
            ops.clone(),
            dir.clone(),
        );
        let bytes = tokio::task::spawn_blocking(move || {
            let mut t =
                ply::load_table(&d2.join(SOURCE_FILE), &limits).map_err(|e| e.to_string())?;
            adjust::bake_view_rotation(&mut t, rot).map_err(|e| e.to_string())?;
            adjust::apply(&mut t, &ops2).map_err(|e| e.to_string())?;
            Ok::<_, String>(t.encode(Some("adjusted by 3D Maker")))
        })
        .await
        .map_err(internal)?
        .map_err(|e| Halt::Failed {
            error: UserError::new(
                ErrorKind::InvalidDesign,
                "The adjustment couldn't be applied",
                format!("{}. Try describing the change differently.", short(&e)),
                NextAction::RetryAll,
            ),
            state: ProjectState::Failed,
        })?;
        self.commit_splat(id, pid, bytes, cancel).await
    }

    /// One model request. Recorded before sending; never retried here. The
    /// raw answer and the parsed result are saved before returning.
    #[allow(clippy::too_many_arguments)]
    async fn ask<T: serde::Serialize>(
        &self,
        id: &str,
        pid: ProviderId,
        provider: Arc<dyn Provider>,
        system: &str,
        user: &str,
        result_file: &str,
        cancel: &CancellationToken,
        parse: impl Fn(&str) -> Result<T, String>,
    ) -> Result<T, Halt> {
        self.set_state(id, ProjectState::Designing);
        let attempt = self
            .store
            .begin_stage(id, StageKind::Design, &provider.model())
            .map_err(internal)?;
        let fail = |error: UserError| {
            let _ = self.store.update_stage(
                id,
                StageKind::Design,
                attempt,
                StageStatus::Failed,
                Some(&error),
            );
            Halt::Failed {
                error,
                state: ProjectState::Failed,
            }
        };
        let answer = tokio::select! {
            r = provider.complete(system, user, cancel) => r,
            _ = cancel.cancelled() => Err(ProviderError::Cancelled),
        };
        let text = match answer {
            Ok(t) => t,
            Err(ProviderError::Cancelled) => {
                let _ = self.store.update_stage(
                    id,
                    StageKind::Design,
                    attempt,
                    StageStatus::Cancelled,
                    None,
                );
                return Err(Halt::Cancelled { designing: true });
            }
            Err(e) => return Err(fail(e.to_user(pid))),
        };
        let dir = self.lib.project_dir(id);
        // The raw answer is kept for troubleshooting; it holds no secrets.
        let _ = write_atomic(&dir, &dir.join(ANSWER_FILE), text.as_bytes(), ".cp-");
        let parsed = parse(&text).map_err(|e| {
            let billed = if pid.bills_per_call() { " (this is billed again)" } else { "" };
            fail(UserError::new(
                ErrorKind::InvalidDesign,
                "The model's answer couldn't be used",
                format!(
                    "{} answered, but {}. Asking again usually works{billed}; a more capable model helps too.",
                    pid.display_name(),
                    short(&e)
                ),
                NextAction::RetryAll,
            ))
        })?;
        let json = serde_json::to_vec_pretty(&parsed).map_err(internal)?;
        write_atomic(&dir, &dir.join(result_file), &json, ".cp-")
            .map_err(|e| fail(e.to_user(pid)))?;
        let _ = self
            .store
            .update_stage(id, StageKind::Design, attempt, StageStatus::Done, None);
        Ok(parsed)
    }

    /// Builds the splat for a design and commits it. Local and free.
    async fn build(
        &self,
        id: &str,
        pid: ProviderId,
        design: &Design,
        cancel: &CancellationToken,
    ) -> Result<(), Halt> {
        if cancel.is_cancelled() {
            return Err(Halt::Cancelled { designing: false });
        }
        self.set_state(id, ProjectState::Building);
        let (budget, d) = (self.cfg.splat_budget, design.clone());
        let bytes = tokio::task::spawn_blocking(move || design::to_ply(&d, budget))
            .await
            .map_err(internal)?;
        self.commit_splat(id, pid, bytes, cancel).await
    }

    /// Writes, validates and atomically commits a finished splat, then marks
    /// the project ready.
    async fn commit_splat(
        &self,
        id: &str,
        pid: ProviderId,
        bytes: Vec<u8>,
        cancel: &CancellationToken,
    ) -> Result<(), Halt> {
        let dir = self.lib.project_dir(id);
        std::fs::create_dir_all(&dir).map_err(|e| Halt::Failed {
            error: ProviderError::from_io(&e).to_user(pid),
            state: ProjectState::NeedsAttention,
        })?;
        let limits = self.cfg.limits;
        let build_dir = dir.clone();
        let built = tokio::task::spawn_blocking(move || {
            let mut tmp = tempfile::Builder::new()
                .prefix(".build-")
                .suffix(".part")
                .tempfile_in(&build_dir)
                .map_err(|e| ProviderError::from_io(&e))?;
            tmp.write_all(&bytes)
                .and_then(|_| tmp.as_file().sync_all())
                .map_err(|e| ProviderError::from_io(&e))?;
            let path = tmp.into_temp_path();
            let summary = ply::validate_file(&path, &limits)
                .map_err(|e| ProviderError::Io(format!("the built splat failed its check: {e}")))?;
            Ok::<_, ProviderError>((path, summary))
        })
        .await
        .map_err(internal)?;
        let (temp, summary) = built.map_err(|e| Halt::Failed {
            error: e.to_user(pid),
            state: ProjectState::NeedsAttention,
        })?;
        if cancel.is_cancelled() {
            return Err(Halt::Cancelled { designing: false });
        }
        self.set_state(id, ProjectState::Saving);
        let dest = dir.join(SPLAT_FILE);
        net::commit(temp, &dest).map_err(|e| Halt::Failed {
            error: e.to_user(pid),
            state: ProjectState::NeedsAttention,
        })?;
        self.store
            .mark_ready(id, &dest.display().to_string(), &summary)
            .map_err(internal)?;
        Ok(())
    }

    fn retry_options(&self, p: &ProjectRow) -> RetryOptions {
        if ProviderId::parse(&p.provider).is_none()
            || p.state == ProjectState::Ready
            || self
                .active
                .lock()
                .unwrap()
                .as_ref()
                .is_some_and(|a| a.project_id == p.id)
        {
            return RetryOptions::default();
        }
        RetryOptions {
            rebuild: self.has_saved_answer(&p.id),
            full: true,
        }
    }

    fn view(&self, p: &ProjectRow, cancel: Option<CancelReport>) -> JobView {
        let name = ProviderId::parse(&p.provider)
            .map(|id| id.display_name())
            .unwrap_or("The model");
        let label = match p.state {
            ProjectState::Queued => "Starting".to_string(),
            ProjectState::Designing => format!("{name} is designing the object"),
            ProjectState::Building => "Building the 3D splat".into(),
            ProjectState::Saving => "Saving object".into(),
            ProjectState::Ready => "Ready".into(),
            ProjectState::Failed => "Failed".into(),
            ProjectState::Cancelled => "Cancelled".into(),
            ProjectState::NeedsAttention => "Needs attention".into(),
        };
        JobView {
            project_id: p.id.clone(),
            state: p.state,
            label,
            error: p.error.clone(),
            cancel,
        }
    }

    fn emit_projects(&self) {
        self.events.projects(&self.summaries());
    }
}

/// Writes `bytes` to `dest` through a temp file in `dir` and an atomic rename.
fn write_atomic(dir: &Path, dest: &Path, bytes: &[u8], prefix: &str) -> Result<(), ProviderError> {
    std::fs::create_dir_all(dir).map_err(|e| ProviderError::from_io(&e))?;
    let mut tmp = tempfile::Builder::new()
        .prefix(prefix)
        .suffix(".part")
        .tempfile_in(dir)
        .map_err(|e| ProviderError::from_io(&e))?;
    tmp.write_all(bytes)
        .and_then(|_| tmp.as_file().sync_all())
        .map_err(|e| ProviderError::from_io(&e))?;
    net::commit(tmp.into_temp_path(), dest)
}

/// Whether a PLY header carries this app's marker comment.
fn header_has_mark(path: &Path) -> bool {
    let mut buf = vec![0u8; 1024];
    let n = std::fs::File::open(path)
        .and_then(|mut f| std::io::Read::read(&mut f, &mut buf))
        .unwrap_or(0);
    let head = &buf[..n];
    let end = head
        .windows(10)
        .position(|w| w == b"end_header")
        .unwrap_or(n);
    let header = &head[..end];
    OWN_PLY_MARKS
        .iter()
        .any(|m| header.windows(m.len()).any(|w| w == *m))
}

fn summary(p: &ProjectRow) -> ProjectSummary {
    ProjectSummary {
        id: p.id.clone(),
        prompt: p.prompt.clone(),
        provider: p.provider.clone(),
        state: p.state,
        created_at: p.created_at,
        thumb_path: p.thumb_path.clone().filter(|t| Path::new(t).exists()),
        splat_count: p.splat_count,
    }
}
