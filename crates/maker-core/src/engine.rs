//! The job engine: asks the selected model for a shape design, saves it,
//! builds the Gaussian splat locally and records the result.
//!
//! Invariants:
//! * A design request is recorded *before* it is sent, and only an explicit
//!   Generate or "Ask again" click sends one. Nothing billable is retried
//!   automatically.
//! * The model's design is saved before the splat is built, so a failed or
//!   interrupted build is redone locally ("Rebuild") without asking again.
//! * Only one generation runs at a time.
//! * A project becomes `ready` only after the splat file was validated and
//!   atomically committed.

// `Halt` carries a full `UserError` for the UI; it is created at most once per
// run, so boxing it would only add noise.
#![allow(clippy::result_large_err)]

