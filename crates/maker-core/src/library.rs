//! On-disk layout and file operations for saved objects.
//!
//! ```text
//! <data>/projects.db
//! <data>/objects/<project-id>/reference.png
//! <data>/objects/<project-id>/splat.ply      (byte-identical to the provider's validated output)
//! <data>/objects/<project-id>/thumb.png      (optional)
//! ```

use crate::errors::ProviderError;
use sha2::{Digest, Sha256};
use std::io::{Read, Write};
use std::path::{Path, PathBuf};

#[derive(Debug, Clone)]
pub struct Library {
    root: PathBuf,
}

impl Library {
    pub fn new(root: impl Into<PathBuf>) -> std::io::Result<Self> {
        let root = root.into();
        std::fs::create_dir_all(root.join("objects"))?;
        Ok(Self { root })
    }
    pub fn root(&self) -> &Path {
        &self.root
    }
    pub fn db_path(&self) -> PathBuf {
        self.root.join("projects.db")
    }
    pub fn objects_dir(&self) -> PathBuf {
        self.root.join("objects")
    }
    pub fn project_dir(&self, id: &str) -> PathBuf {
        // ids are UUIDs generated by us; refuse anything that could escape.
        let safe: String = id
            .chars()
            .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
            .collect();
        self.objects_dir().join(safe)
    }

    /// Removes leftovers of interrupted builds/copies. Only temp files with
    /// our prefixes are touched; completed assets are never deleted.
    pub fn cleanup_partials(&self) -> usize {
        let mut removed = 0;
        let Ok(dirs) = std::fs::read_dir(self.objects_dir()) else {
            return 0;
        };
        for d in dirs.flatten() {
            let Ok(files) = std::fs::read_dir(d.path()) else {
                continue;
            };
            for f in files.flatten() {
                let name = f.file_name().to_string_lossy().to_string();
                if [".dl-", ".cp-", ".build-"]
                    .iter()
                    .any(|p| name.starts_with(p))
                    && name.ends_with(".part")
                    && std::fs::remove_file(f.path()).is_ok()
                {
                    removed += 1;
                }
            }
        }
        removed
    }

    pub fn remove_project_dir(&self, id: &str) {
        let dir = self.project_dir(id);
        if dir.starts_with(self.objects_dir()) && dir != self.objects_dir() {
            let _ = std::fs::remove_dir_all(dir);
        }
    }
}

/// Copies `src` to `dest` byte-for-byte via a temp file in the destination
/// directory, verifying the SHA-256 against `expected_sha` before the atomic
/// rename. Returns (bytes, sha256).
pub fn verified_copy(
    src: &Path,
    dest: &Path,
    expected_sha: Option<&str>,
) -> Result<(u64, String), ProviderError> {
    let dir = dest
        .parent()
        .ok_or_else(|| ProviderError::Io("destination has no folder".into()))?;
    std::fs::create_dir_all(dir).map_err(|e| ProviderError::from_io(&e))?;
    let mut input = std::fs::File::open(src).map_err(|e| ProviderError::from_io(&e))?;
    let mut tmp = tempfile::Builder::new()
        .prefix(".cp-")
        .suffix(".part")
        .tempfile_in(dir)
        .map_err(|e| ProviderError::from_io(&e))?;
    let mut hasher = Sha256::new();
    let mut buf = vec![0u8; 1 << 20];
    let mut total = 0u64;
    loop {
        let n = input
            .read(&mut buf)
            .map_err(|e| ProviderError::from_io(&e))?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
        tmp.write_all(&buf[..n])
            .map_err(|e| ProviderError::from_io(&e))?;
        total += n as u64;
    }
    tmp.as_file()
        .sync_all()
        .map_err(|e| ProviderError::from_io(&e))?;
    let sha = hex::encode(hasher.finalize());
    if let Some(exp) = expected_sha {
        if !exp.eq_ignore_ascii_case(&sha) {
            return Err(ProviderError::Io(
                "The saved splat no longer matches its recorded checksum; it may have been modified or damaged on disk.".into(),
            ));
        }
    }
    crate::net::commit(tmp.into_temp_path(), dest)?;
    Ok((total, sha))
}

pub fn file_sha256(path: &Path) -> std::io::Result<String> {
    let mut f = std::fs::File::open(path)?;
    let mut h = Sha256::new();
    let mut buf = vec![0u8; 1 << 20];
    loop {
        let n = f.read(&mut buf)?;
        if n == 0 {
            break;
        }
        h.update(&buf[..n]);
    }
    Ok(hex::encode(h.finalize()))
}
